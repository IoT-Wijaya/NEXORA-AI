void test_amplop_sah_diterima_dan_manifest_terisi()
{
    Manifest m;
    memset(&m, 0, sizeof(m));
    const auto r = SignedManifestParser::parse(GOOD, sizeof(GOOD), PUB, m);
    TEST_ASSERT_TRUE(r.ok());
    TEST_ASSERT_EQUAL_STRING("sanding-kecil", m.deviceType);
    TEST_ASSERT_EQUAL_UINT32(7, m.build);
    TEST_ASSERT_EQUAL_UINT32(340877, m.size);
    TEST_ASSERT_EQUAL_UINT8(0xab, m.sha256[0]);
    TEST_ASSERT_EQUAL_UINT8(0xab, m.sha256[31]);
}

void test_satu_bit_isi_berubah_ditolak_dan_out_utuh()
{
    uint8_t rusak[sizeof(GOOD)];
    memcpy(rusak, GOOD, sizeof(GOOD));
    rusak[64 + 20] ^= 0x01;
    Manifest m;
    memset(&m, 0x5a, sizeof(m));
    const auto r = SignedManifestParser::parse(rusak, sizeof(rusak), PUB, m);
    TEST_ASSERT_EQUAL(SignedManifestError::BadSignature, r.error);
    TEST_ASSERT_EQUAL_UINT8(0x5a, ((const uint8_t *)&m)[0]);
    TEST_ASSERT_EQUAL_UINT32(0x5a5a5a5a, m.build);
}

void test_tanda_tangan_rusak_ditolak()
{
    uint8_t rusak[sizeof(GOOD)];
    memcpy(rusak, GOOD, sizeof(GOOD));
    rusak[3] ^= 0x80;
    Manifest m;
    const auto r = SignedManifestParser::parse(rusak, sizeof(rusak), PUB, m);
    TEST_ASSERT_EQUAL(SignedManifestError::BadSignature, r.error);
}

void test_kunci_lain_ditolak()
{
    uint8_t lain[32];
    memcpy(lain, PUB, 32);
    lain[0] ^= 0x01;
    Manifest m;
    const auto r = SignedManifestParser::parse(GOOD, sizeof(GOOD), lain, m);
    TEST_ASSERT_EQUAL(SignedManifestError::BadSignature, r.error);
}

void test_isi_dipotong_ditolak()
{
    Manifest m;
    const auto r = SignedManifestParser::parse(GOOD, sizeof(GOOD) - 1, PUB, m);
    TEST_ASSERT_EQUAL(SignedManifestError::BadSignature, r.error);
}

void test_hanya_tanda_tangan_tanpa_isi_terlalu_pendek()
{
    Manifest m;
    TEST_ASSERT_EQUAL(SignedManifestError::TooShort,
                      SignedManifestParser::parse(GOOD, 64, PUB, m).error);
    TEST_ASSERT_EQUAL(SignedManifestError::TooShort,
                      SignedManifestParser::parse(GOOD, 0, PUB, m).error);
    TEST_ASSERT_EQUAL(SignedManifestError::TooShort,
                      SignedManifestParser::parse(nullptr, 100, PUB, m).error);
}

void test_terlalu_besar_ditolak_sebelum_verifikasi()
{
    static uint8_t besar[64 + 1024 + 1];
    memset(besar, 'x', sizeof(besar));
    Manifest m;
    TEST_ASSERT_EQUAL(SignedManifestError::TooLarge,
                      SignedManifestParser::parse(besar, sizeof(besar), PUB, m).error);
}

void test_tanda_tangan_sah_tapi_isi_buruk_dilaporkan_sebagai_BadManifest()
{
    Manifest m;
    const auto r = SignedManifestParser::parse(NOSHA, sizeof(NOSHA), PUB, m);
    TEST_ASSERT_EQUAL(SignedManifestError::BadManifest, r.error);
    TEST_ASSERT_EQUAL(ManifestError::MissingField, r.manifest.error);
    TEST_ASSERT_EQUAL_STRING("sha256", r.manifest.field);
}

void test_kunci_nol_ditolak()
{
    uint8_t nol[32] = {0};
    Manifest m;
    TEST_ASSERT_EQUAL(SignedManifestError::BadSignature,
                      SignedManifestParser::parse(GOOD, sizeof(GOOD), nol, m).error);
}

